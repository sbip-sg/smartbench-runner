#!/usr/bin/env python3

"""Module handling Smartian analyzer."""

# Standard Library
import math
import os
import re

from typing import List, Optional, Tuple, Union

# Library
from smartbench import logger, solc
from smartbench.annotation import BugAnnot
from smartbench.docker import DockerContainer
from smartbench.issue import Checker, Confidence, Issue, IssueKind, Severity
from smartbench.loc import Location
from smartbench.printer import debug, warning
from smartbench.tools.tool import Tool


SMARTIAN_DIR = os.path.dirname(__file__)


class Smartian(Tool):
    def __init__(
        self,
        id: str,
        name: str,
        executable: str,
        default_arguments: str,
        default_timeout: int,
        additional_args: Optional[str] = None,
        random_seed: int = 0,
    ):
        Tool.__init__(
            self,
            id,
            name,
            executable,
            default_arguments,
            default_timeout,
            additional_args,
            random_seed,
        )

    def make_analysis_command(
        self,
        test_file: str,
        contracts: List[str],
        test_output_dir: str,
        container=Optional[DockerContainer],
        timeout: Optional[int] = None,
    ) -> str:
        """Function to make analysis command for `Smartian`. This function should
        have the same signature with other tools.

        """

        if container is not None:
            cmd = f"docker exec -it {container.name} /root/{self.executable}"
        else:
            cmd = os.path.join(SMARTIAN_DIR, self.executable)

        # Input file must be the first argument to be run by docker
        cmd = cmd + " " + test_file

        # Pass contract names to Smartian
        if len(contracts) > 0:
            cmd = cmd + " -c " + " ".join(contracts)

        # Pass arguments
        if self.default_arguments:
            cmd = cmd + " " + self.default_arguments
        if self.additional_args:
            cmd = cmd + " " + self.additional_args

        # Calculate timeout for each contract if it is not specified in
        # additional arguments of Confuzzius
        if self.additional_args is None or (
            "-t " not in self.additional_args
            and "--timelimit " not in self.additional_args
        ):
            timeout = self.default_timeout if timeout is None else timeout
            contract_timeout = math.ceil(timeout / len(contracts))
            cmd = cmd + " -t " + str(contract_timeout)

        output_file = self.configure_output_file(test_output_dir)

        cmd = cmd + " --outputdir " + test_output_dir

        return cmd

    def parse_issue_location(self, log_file) -> Union[Location, None]:
        """Parse source location in backtrace elements generated by Smartian."""
        file_path = logger.get_input_test_file(log_file)
        return Location(file_path, 0, 0, 0, 0)

    def process_analysis_result(self, test_output_dir: str) -> List[Issue]:
        """Parse output of Smartian"""
        output_file = os.path.join(test_output_dir, self.output_file)
        log_file = os.path.join(test_output_dir, self.log_file)
        debug("Smartian output_file: ", output_file)
        output_file_data = open(output_file, "r", encoding="utf-8")
        data = output_file_data.read()
        kinds = []

        assert_failure_match = re.search(r"Assertion Failure: [0-9]+", data)
        if assert_failure_match:
            assert_failure = assert_failure_match.group()
            assert_failure_num = assert_failure.removeprefix(
                "Assertion Failure: "
            )
            if int(assert_failure_num) > 0:
                kinds.append(IssueKind.ASSERTION_FAILURE)

        arbitrary_write_match = re.search(r"Suicidal Contract: [0-9]+", data)
        if arbitrary_write_match:
            arbitrary_write_dep = arbitrary_write_match.group()
            arbitrary_write_num = arbitrary_write_dep.removeprefix(
                "Suicidal Contract: "
            )
            if int(arbitrary_write_num) > 0:
                kinds.append(IssueKind.ARBITRARY_WRITE)

        blk_dep_match = re.search(r"Block state Dependency: [0-9]+", data)
        if blk_dep_match:
            blk_dep = blk_dep_match.group()
            blk_dep_num = blk_dep.removeprefix("Block state Dependency: ")
            if int(blk_dep_num) > 0:
                kinds.append(IssueKind.BLOCK_DEPENDENCY)

        delegatecall_match = re.search(r"Control Hijack: [0-9]+", data)
        if delegatecall_match:
            delegatecall_dep = delegatecall_match.group()
            delegatecall_num = delegatecall_dep.removeprefix("Control Hijack: ")
            if int(delegatecall_num) > 0:
                kinds.append(IssueKind.UNSAFE_DELEGATECALL)

        leaking_ether_match = re.search(r"Ether Leak: [0-9]+", data)
        if leaking_ether_match:
            leaking_ether_dep = leaking_ether_match.group()
            leaking_ether_num = leaking_ether_dep.removeprefix("Ether Leak: ")
            if int(leaking_ether_num) > 0:
                kinds.append(IssueKind.LEAKING_ETHER)

        integer_match = re.search(r"Integer Bug: [0-9]+", data)
        if integer_match:
            integer_dep = integer_match.group()
            integer_num = integer_dep.removeprefix("Integer Bug: ")
            if int(integer_num) > 0:
                kinds.append(IssueKind.INTEGER_BUG)

        exception_match = re.search(r"Mishandled Exception: [0-9]+", data)
        if exception_match:
            exception_dep = exception_match.group()
            exception_num = exception_dep.removeprefix("Mishandled Exception: ")
            if int(exception_num) > 0:
                kinds.append(IssueKind.UNHANDLED_EXCEPTION)

        reentrancy_match = re.search(r"Reentrancy: [0-9]+", data)
        if reentrancy_match:
            reentrancy_dep = reentrancy_match.group()
            reentrancy_num = reentrancy_dep.removeprefix("Reentrancy: ")
            if int(reentrancy_num) > 0:
                kinds.append(IssueKind.REENTRANCY)

        selfdestruct_match = re.search(r"Suicidal Contract: [0-9]+", data)
        if selfdestruct_match:
            selfdestruct_dep = selfdestruct_match.group()
            selfdestruct_num = selfdestruct_dep.removeprefix(
                "Suicidal Contract: "
            )
            if int(selfdestruct_num) > 0:
                kinds.append(IssueKind.UNSAFE_SELFDESTRUCT)

        tx_origin_match = re.search(r"Transaction Origin Use: [0-9]+", data)
        if tx_origin_match:
            tx_origin_dep = tx_origin_match.group()
            tx_origin_num = tx_origin_dep.removeprefix(
                "Transaction Origin Use: "
            )
            if int(tx_origin_num) > 0:
                kinds.append(IssueKind.TRANSACTION_ORDER_DEPENDENCY)

        locking_ether_match = re.search(r"Freezing Ether: [0-9]+", data)
        if locking_ether_match:
            locking_ether_dep = locking_ether_match.group()
            locking_ether_num = locking_ether_dep.removeprefix(
                "Freezing Ether: "
            )
            if int(locking_ether_num) > 0:
                kinds.append(IssueKind.LOCKING_ETHER)

        require_violation_match = re.search(
            r"Requirement Violation: [0-9]+", data
        )
        if require_violation_match:
            require_violation_dep = require_violation_match.group()
            require_violation_num = require_violation_dep.removeprefix(
                "Requirement Violation: "
            )
            if int(require_violation_num) > 0:
                kinds.append(IssueKind.REQUIREMENT_VIOLATION)

        checker = Checker("Smartian", "fuzzing")
        issues = []
        location = self.parse_issue_location(log_file)
        for kind in kinds:
            issue = Issue(
                kind,
                "",
                Severity.UNKNOWN,
                Confidence.UNKNOWN,
                location,
                checker,
            )
            issues.append(issue)

        return issues

    def match_location_of_issue_to_annotation(
        self, issue: Issue, annot: BugAnnot
    ):
        """Function to check whether an reported issue is related to a bug
        annotation."""
        return issue.issue_kind == annot.annot_kind

    def parse_instruction_coverage(self, test_output_dir: str):
        """Parse code coverage of Smartian"""
        output_file = os.path.join(test_output_dir, self.output_file)

        lines = None
        with open(output_file, "r", encoding="utf-8") as file:
            try:
                lines = [line.rstrip() for line in file]
            except ValueError:
                warning("Failed to parse Smartian output file:", output_file)
                return []

        results = [(0, 0)]
        count = 1
        current_time = 0
        for line in lines:
            match_str = re.search(r"Covered Instructions: [0-9]+", line)
            time_str = re.search(
                "(\d{2})[/.:](\d{2})[/.:](\d{2})[/.:](\d{2})", line
            )
            if match_str and time_str:
                time = time_str.group()
                seconds = int(time[9:11])
                minutes = int(time[6:8])
                hours = int(time[3:5])
                duration = hours * 3600 + minutes * 60 + seconds
                if duration - current_time >= 1:
                    coverage = match_str.group()
                    coverage = coverage.removeprefix("Covered Instructions: ")
                    results.append((duration, int(coverage)))
                    current_time = duration
                count += 1

        return results

def make_analysis_command(
    executable_file: str,
    arguments: str,
    test_file: str,
    output_file: str,
    solc_path: str,
    timeout: int,
):
    """Function to make analysis command for `Smartian`. This function should
    have the same signature with other tools.

    """

    command = executable_file

    if arguments:
        command = command + " " + arguments

    output_dir = os.path.basename(output_file)
    command = (
        command
        + " fuzz "
        + " -p "
        # bytecode file
        + " -a "
        # abi file
        + " -t "
        + str(timeout)
        + " -o "
        + output_dir
    )




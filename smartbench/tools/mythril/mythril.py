#!/usr/bin/env python3

"""Module handling Mythril."""

# Standard Library
import json
import os

from typing import List, Optional

# Library
from smartbench import issue, logger
from smartbench.annotation import BugAnnot
from smartbench.docker import DockerContainer
from smartbench.issue import Checker, Confidence, Issue, IssueKind, Severity
from smartbench.printer import debug, error, warning
from smartbench.solidity.loc import Location
from smartbench.tools.tool import Tool


class Mythril(Tool):
    def __init__(
        self,
        id: str,
        name: str,
        executable: str,
        default_args: str,
        default_timeout: int,
        additional_args: Optional[str] = None,
        random_seed: int = 0,
    ):
        Tool.__init__(
            self,
            id,
            name,
            executable,
            default_args,
            default_timeout,
            additional_args,
            random_seed,
        )

    def make_analysis_command(
        self,
        test_file: str,
        contracts: List[str],
        test_output_dir: str,
        container: DockerContainer,
        solc_version: str,
        timeout: Optional[int] = None,
    ) -> str:
        """Function to make analysis command for `Mythril`. This function should
        have the same signature with other tools."""

        # Configure command
        cmd = f"docker exec -it {container.name} /root/{self.executable}"

        # Input file and contract names
        cmd += f" -f {test_file}"

        # Solc version
        if solc_version is not None:
            cmd += f" --solc-version {solc_version}"

        # Output file
        if output_file := self.configure_json_result_file(test_output_dir):
            cmd += f" -o {output_file}"

        # Timeout
        timeout = self.default_timeout if timeout is None else timeout
        cmd += f" -t {str(timeout)}"

        # Finally, pass default and additional arguments
        if self.default_arguments:
            cmd += f" {self.default_arguments}"
        if self.additional_args:
            cmd += f" {self.additional_args}"

        return cmd

    def parse_severity(self, severity: Optional[str]) -> Optional[Severity]:
        """Parse severity level of issue detected by Mythril."""
        if severity is None:
            return None

        severity = severity.casefold()

        if severity == "low":
            return Severity.LOW_RISK

        if severity == "medium":
            return Severity.MEDIUM_RISK

        if severity == "high":
            return Severity.HIGH_RISK

        warning(f"Unknown severity: {severity}")

        return None

    def parse_issue_location(
        self, log_file, start_line, end_line
    ) -> List[Location]:
        """Parse source location in backtrace elements generated by Mythril."""
        if file_path := logger.get_input_test_file(log_file):
            loc = Location(
                file_path=file_path, start_line=start_line, end_line=end_line
            )
            return [loc]
        return []

    def parse_issue_kind(self, description: str) -> IssueKind:
        """Parse issue kind from issue description reported by Mythril"""
        # SWC 127
        # if "Jump to an arbitrary instruction" in description:
        #     return IssueKind.ABITRARY_JUMP

        # SWC 124
        if "Write to an arbitrary storage location" in description:
            return IssueKind.WRITE_TO_ARBITRARY_STORAGE_LOCATION

        # SWC 112
        if "Delegatecall to user-supplied address" in description:
            return IssueKind.UNSAFE_DELEGATECALL

        # SWC 115
        if "Dependence on tx.origin" in description:
            return IssueKind.AUTHORIZATION_THROUGH_TX_ORIGIN

        # SWC 116 + 120
        if "Dependence on predictable environment variable" in description:
            return IssueKind.BLOCK_VALUE_DEPENDENCY

        # SWC 105
        if "Unprotected Ether Withdrawal" in description:
            return IssueKind.LEAKING_ETHER

        # SWC 110
        if "Exception State" in description:
            return IssueKind.ASSERTION_FAILURE

        # SWC 107
        if "External Call To User-Supplied Address" in description:
            return IssueKind.REENTRANCY

        # SWC 101
        if "Integer Arithmetic Bugs" in description:
            return IssueKind.INTEGER_BUG

        # SWC 113
        if "Multiple Calls in a Single Transaction" in description:
            return IssueKind.DENIAL_OF_SERVICE_WITH_FAILED_CALL

        # SWC 107
        if "State access after external call" in description:
            return IssueKind.REENTRANCY

        # SWC 106
        if "Unprotected Selfdestruct" in description:
            return IssueKind.UNSAFE_SELFDESTRUCT

        # SWC 104
        if "Unchecked return value from external call" in description:
            return IssueKind.UNCHECKED_CALL_RETURN_VALUE

        return IssueKind.UNKNOWN

    def parse_analysis_output(
        self, test_output_dir: str
    ) -> Optional[List[Issue]]:
        """Parse output of Mythril"""
        output = None
        output_file = os.path.join(test_output_dir, self.json_result_file)
        log_file = self.configure_log_file(test_output_dir)
        debug("Mythril parse file: ", output_file)
        try:
            with open(output_file, "r", encoding="utf-8") as file:
                output = json.load(file)
        except Exception as err:
            error(f"Failed to parse Mythril output: {output_file}\n\n{err}")
            return []

        try:
            reported_bugs = output.get("issues")

            all_issues = []

            for bug in reported_bugs:
                checker = Checker("mythril", "symbolic execution")
                kind = self.parse_issue_kind(bug.get("title"))
                start_line = bug.get("lineno")
                code = bug.get("code")
                if code is None:
                    end_line = start_line
                else:
                    end_line = start_line + code.count("\n")

                loc = self.parse_issue_location(log_file, start_line, end_line)
                severity = self.parse_severity(bug.get("severity"))

                all_issues = issue.record_new_issue_and_deduplicate(
                    all_issues,
                    kind,
                    "",
                    loc,
                    checker,
                    severity=severity,
                )

            return all_issues
        except ValueError:
            return []

    def match_location_of_issue_to_annotation(
        self, issue: Issue, annot: BugAnnot
    ) -> bool:
        """Check whether the location of an issue is relevant to the location of
        a bug annotation.
        """

        # Find if a bug location matches with the annotation location.
        for iloc in issue.locations:
            # The bug line number must be reported explicitly by Mythril
            if iloc.start_line is None or iloc.end_line is None:
                return False

            # Mythril reports issue location as a single line.
            # If an issue and a bug annotation are relevant, then the bug
            # annotation's location should cover the issue's location.

            if (
                iloc.start_line >= annot.start_line
                and iloc.end_line <= annot.end_line
            ):
                return True

        return False

#!/usr/bin/env python3

"""Module handling sFuzz."""

import os
import re
import subprocess
import shlex
from typing import List, Union

# Library
from smartbench import log
from smartbench.debug import debug, warning
from smartbench.issue import Checker, Confidence, Issue, IssueKind, Severity
from smartbench.location import Location
from smartbench.bug_annot import BugAnnot

# Tool name
TOOL_NAME = "sFuzz"

def make_analysis_command(
    executable_file: str,
    arguments: str,
    test_file: str,
    output_file: str,
    solc_path: str,
    timeout: int,
):
    """
    Function to make analysis command for Slither.
    This function should have the same signature with other tools.
    """
    command = executable_file

    if arguments:
        command = command + " " + arguments

    solc_version = os.path.basename(solc_path)
    solc_version.removeprefix("solc-")

    command = (
        command
        + " "
        + test_file
        + " "
        + str(timeout)
        + " "
        + solc_version
    )
    print(f"sfuzz command: {command}")
    return command

def parse_rule(rule: str) -> Checker:
    """Parser checker of sFuzz"""
    return Checker("sFuzz", rule)

def parse_source_location(log_file) -> Union[Location, None]:
    """Parse source location in backtrace elements generated by sFuzz."""
    file_path = log.get_input_test_file(log_file)
    return Location(file_path, 0, 0, 0, 0)

def parse_issue_kind(description: str) -> IssueKind:
    if "exception disorder : found" in description:
        return IssueKind.UNHANDLED_EXCEPTION;

    if "reentrancy : found" in description:
        return IssueKind.REENTRANCY

    if "integer overflow : found" in description:
        return IssueKind.INTEGER_BUG

    if "integer underflow : found" in description:
        return IssueKind.INTEGER_BUG

    if "dangerous delegatecall : found" in description:
        return IssueKind.UNSAFE_DELEGATECALL

    if "freezing ether : found" in description:
        return IssueKind.LOCKING_ETHER

    if "block number dependency : found" in description:
        return IssueKind.BLOCK_DEPENDENCY

    if "timestamp dependency : found" in description:
        return IssueKind.BLOCK_DEPENDENCY

    return IssueKind.UNKNOWN

def parse_sfuzz_json_output(_output_file: str, log_file: str) -> List[Issue]:
    """Parse output of sFuzz"""
    lines = None
    debug("sFuzz log_file: ", log_file)
    with open(log_file, "r", encoding="utf-8") as file:
        try:
            lines = [line.rstrip() for line in file]
        except ValueError:
            warning("Failed to parse sFuzz log file:", log_file)
            return []

    if lines is None:
        warning("Failed to parse sFuzz log file:", log_file)
        return []

    kinds = []
    checker = parse_rule("fuzzing")
    for line in lines:
        kind = parse_issue_kind(line)
        if kind != IssueKind.UNKNOWN:
            if kind not in kinds:
                kinds.append(kind)

    issues = []
    location = parse_source_location(log_file)
    for kind in kinds:
        issue = Issue(
            kind,
            "",
            Severity.UNKNOWN,
            Confidence.UNKNOWN,
            location,
            checker,
        )
        issues.append(issue)

    return issues;

def check_issue_kind(kind: IssueKind, bug_name: str):
    if kind == IssueKind.BLOCK_DEPENDENCY:
        return bug_name == "TIME_MANIPULATION" or bug_name == "BAD_RANDOMNESS"

    if kind == IssueKind.INTEGER_BUG:
        return bug_name == "ARITHMETIC";

    if kind == IssueKind.UNHANDLED_EXCEPTION:
        return bug_name == "UNCHECKED_LL_CALLS";

    if str(kind).casefold() != bug_name.casefold():
        return False;
    return True

def match_location_of_issue_to_annotation(issue: Issue, annot: BugAnnot):
    """Function to check whether an reported issue is related to a bug
    annotation."""

    # Check for issue kind
    if not check_issue_kind(issue.issue_kind, annot.bug_name):
        return False

    return True

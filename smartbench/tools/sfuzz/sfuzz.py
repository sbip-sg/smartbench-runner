def parse_rule(rule: str) -> Checker:
    """Parser checker of sFuzz"""
    return Checker("sFuzz", rule)

def parse_source_location(log_file) -> Union[Location, None]:
    """Parse source location in backtrace elements generated by sFuzz."""
    file_path = log.get_input_test_file(log_file)
    return Location(file_path, 0, 0, 0, 0)

def parse_issue_kind(description: str) -> IssueKind:
    if "MishandledException" in description:
        return IssueKind.UNHANDLED_EXCEPTION;

    if "Reentrancy" in description:
        return IssueKind.REENTRANCY

    if "IntegerBug" in description:
        return IssueKind.INTEGER_BUG

    if "DeletegateCall" in description:
        return IssueKind.UNSAFE_DELEGATECALL

    if "LockEther" in description:
        return IssueKind.LOCKING_ETHER

    if "BlockstateDependency" in description:
        return IssueKind.BLOCK_DEPENDENCY

    return IssueKind.UNKNOWN

def parse_sfuzz_coverage(log_file: str) -> int:
    lines = None
    with open(log_file, "r", encoding="utf-8") as file:
        try:
            lines = [line.rstrip() for line in file]
        except ValueError:
            warning("Failed to parse sFuzz log file:", log_file)
            return 0

    result = 0
    x_axis = [0]
    count = 1
    y_axis = [0]
    for line in lines:
        match_str = re.search(r"coverage : [0-9]+", line)
        if match_str:
            coverage = match_str.group()
            x_axis.append(count)
            coverage = coverage.removeprefix("coverage : ")
            y_axis.append(int(coverage))
            count += 1
            result = coverage

    # plotting the points
    plt.plot(x_axis, y_axis)

    # naming the x axis
    plt.xlabel('Time (s)')
    # naming the y axis
    plt.ylabel('Coverage')

    # giving a title to my graph
    plt.title('Code coverage graph!')

    dir_path = os.path.dirname(os.path.realpath(log_file))
    print("path: ", dir_path)
    coverage_path = os.path.join(dir_path, "coverage.png")

    # function to show the plot
    plt.savefig(coverage_path)
    return int(result);

def parse_sfuzz_json_output(output_file: str, log_file: str) -> List[Issue]:
    """Parse output of sFuzz"""
    lines = None
    debug("sFuzz output_file: ", output_file)
    with open(output_file, "r", encoding="utf-8") as file:
        try:
            lines = [line.rstrip() for line in file]
        except ValueError:
            warning("Failed to parse sFuzz output file:", output_file)
            return []

    if lines is None:
        warning("Failed to parse sFuzz's output file:", output_file)
        return []

    issues = []
    checker = parse_rule("fuzzing")
    for line in lines:
        kind = parse_issue_kind(line)
        location = parse_source_location(log_file)
        if kind != IssueKind.UNKNOWN:
            issue = Issue(
                kind,
                "",
                Severity.UNKNOWN,
                Confidence.UNKNOWN,
                location,
                checker,
            )
            issues.append(issue)
    return issues;

def check_issue_kind(kind: IssueKind, bug_name: str):
    if kind == IssueKind.BLOCK_DEPENDENCY:
        return bug_name == "TIME_MANIPULATION" or bug_name == "BAD_RANDOMNESS"

    if kind == IssueKind.INTEGER_BUG:
        return bug_name == "ARITHMETIC";

    if kind == IssueKind.UNHANDLED_EXCEPTION:
        return bug_name == "UNCHECKED_LL_CALLS";

    if str(kind).casefold() != bug_name.casefold():
        return False;
    return True

def match_location_of_issue_to_annotation(issue: Issue, annot: BugAnnot):
    """Function to check whether an reported issue is related to a bug
    annotation."""

    # Check for issue kind
    if not check_issue_kind(issue.issue_kind, annot.bug_name):
        return False

    return True

#!/usr/bin/env python3

"""Module handling sFuzz."""

# Standard Library
import os

from typing import List, Union, Optional

# Library
from smartbench import log, solc
from smartbench.bug_annot import BugAnnot
from smartbench.debug import debug, warning
from smartbench.issue import Checker, Confidence, Issue, IssueKind, Severity
from smartbench.loc import Location
from smartbench.tools.tool import Tool

# Tool name
TOOL_NAME = "sFuzz"

class SFuzz(Tool):

    def __init__(
        self,
        id: str,
        name: str,
        homepage: str,
        category: str,
        path: str,
        default_arguments: str,
        default_timeout: int,
        additional_arguments: Optional[str] = None,
    ):
        Tool.__init__(
            self,
            id,
            name,
            homepage,
            category,
            path,
            default_arguments,
            default_timeout,
            additional_arguments,
        )

    def make_analysis_command(
            self,
            executable_file: str,
            arguments: str,
            test_file: str,
            output_file: str,
            timeout=int,
    ):
        """
        Function to make analysis command for Slither.
        This function should have the same signature with other tools.
        """
        command = executable_file

        if arguments:
            command = command + " " + arguments

        # Configure Solc version the test file
        solc_version = solc.detect_required_solc_version(test_file)

        command = (
        command
            + " "
            + test_file
            + " "
            + str(timeout)
            + " "
            + solc_version
            + " "
            + output_file
        )
        print(f"sfuzz command: {command}")
        return command



    def parse_issue_location(self, log_file) -> Union[Location, None]:
        """Parse source location in backtrace elements generated by sFuzz."""
        file_path = log.get_input_test_file(log_file)
        return Location(file_path, 0, 0, 0, 0)


    def parse_issue_kind(self, description: str) -> IssueKind:
        if "exception disorder : found" in description:
            return IssueKind.UNHANDLED_EXCEPTION

        if "reentrancy : found" in description:
            return IssueKind.REENTRANCY

        if "integer overflow : found" in description:
            return IssueKind.INTEGER_BUG

        if "integer underflow : found" in description:
            return IssueKind.INTEGER_BUG

        if "dangerous delegatecall : found" in description:
            return IssueKind.UNSAFE_DELEGATECALL

        if "freezing ether : found" in description:
            return IssueKind.LOCKING_ETHER

        if "block number dependency : found" in description:
            return IssueKind.BLOCK_DEPENDENCY

        if "timestamp dependency : found" in description:
            return IssueKind.BLOCK_DEPENDENCY

        return IssueKind.UNKNOWN


    def parse_sfuzz_json_output(self, output_file: str, log_file: str) -> List[Issue]:
        """Parse output of sFuzz"""
        lines = None
        debug("sFuzz log_file: ", log_file)
        with open(log_file, "r", encoding="utf-8") as file:
            try:
                lines = [line.rstrip() for line in file]
            except ValueError:
                warning("Failed to parse sFuzz log file:", log_file)
                return []

        if lines is None:
            warning("Failed to parse sFuzz log file:", log_file)
            return []

        kinds = []
        checker = Checker("sFuzz", "fuzzing")

        for line in lines:
            kind = self.parse_issue_kind(line)
            if kind != IssueKind.UNKNOWN:
                if kind not in kinds:
                    kinds.append(kind)

        issues = []
        location = self.parse_issue_location(log_file)
        for kind in kinds:
            issue = Issue(
                kind,
                "",
                Severity.UNKNOWN,
                Confidence.UNKNOWN,
                location,
                checker,
            )
            issues.append(issue)

        return issues


    def check_issue_kind(self, issue_kind: IssueKind, annotation_kind: IssueKind):
        """Function to check whether an reported issue is related to a bug"""
        return issue_kind == annotation_kind

    def match_location_of_issue_to_annotation(self, issue: Issue, annot: BugAnnot):
        """Function to check whether an reported issue is related to a bug
        annotation."""

        # Check for issue kind
        return self.check_issue_kind(issue.issue_kind, annot.annot_kind);

#!/usr/bin/env python3

"""Module handling ILF."""

# Standard Library
import json
import math
import os

from typing import List, Optional, Union

# Library
from smartbench import logger
from smartbench.docker import DockerContainer
from smartbench.issue import Checker, Confidence, Issue, IssueKind, Severity
from smartbench.printer import debug, warning
from smartbench.solidity.loc import Location
from smartbench.tools.tool import Tool
from smartbench.printer import debug, error_traceback


# Configure some paths
ILF_DIR = os.path.dirname(__file__)


class Ilf(Tool):
    def __init__(
        self,
        id: str,
        name: str,
        executable: str,
        default_arguments: str,
        default_timeout: int,
        additional_args: Optional[str] = None,
        random_seed: int = 0,
    ):
        Tool.__init__(
            self,
            id,
            name,
            executable,
            default_arguments,
            default_timeout,
            additional_args,
            random_seed,
        )

    def make_analysis_command(
        self,
        test_file: str,
        contracts: List[str],
        test_output_dir: str,
        solc_version: Optional[str] = None,
        container: Optional[DockerContainer] = None,
        timeout: Optional[int] = None,
    ) -> str:
        """Function to make analysis command for ILF. This function should have
        the same signature with other tools."""

        # Executable file
        if container is not None:
            cmd = f"docker exec -it {container.name} /root/{self.executable}"
        else:
            cmd = os.path.join(ILF_DIR, self.executable)

        # Input file and contract names
        cmd = cmd + " -f " + test_file
        if len(contracts) > 0:
            cmd = cmd + " -c " + " ".join(contracts)

        # Solc version
        if solc_version is not None:
            cmd = cmd + " --solc-version " + solc_version

        # Output directory
        cmd = cmd + " -o " + test_output_dir

        # Calculate timeout for each contract if it is not specified in
        # additional arguments of Confuzzius
        if self.additional_args is None or (
            "--timeout " not in self.additional_args
        ):
            timeout = self.default_timeout if timeout is None else timeout
            contract_timeout = math.ceil(timeout / len(contracts))
            cmd = cmd + " -t " + str(contract_timeout)

        # Finally, pass default and additional arguments
        if self.default_arguments:
            cmd = cmd + " " + self.default_arguments
        if self.additional_args:
            cmd = cmd + " " + self.additional_args

        return cmd

    def parse_issue_kind(self, bug_name: str) -> IssueKind:
        """Parse issue kind from issue description reported by ILF"""
        if bug_name == "BlockStateDep":
            return IssueKind.BLOCK_DEPENDENCY

        if bug_name ==  "DangerousDelegatecall":
            return IssueKind.UNSAFE_DELEGATECALL

        if bug_name ==  "Leaking":
            return IssueKind.LEAKING_ETHER

        if bug_name ==  "Locking":
            return IssueKind.LOCKING_ETHER

        if bug_name == "Suicidal":
            return IssueKind.UNSAFE_SELFDESTRUCT

        if bug_name == "UnhandledException":
            return IssueKind.UNHANDLED_EXCEPTION

        if bug_name == "Reentrancy":
            return IssueKind.REENTRANCY

        return IssueKind.UNKNOWN


    def parse_issue_location(self, log_file) -> Union[Location, None]:
        """Parse source location in backtrace elements generated by sFuzz."""
        file_path = logger.get_input_test_file(log_file)
        return Location(file_path, 0, 0, 0, 0)

    def parse_analysis_output(self, test_output_dir: str) -> List[Issue]:
        """Parse output of ILF"""
        lines = None
        log_file = self.configure_log_file(test_output_dir)
        debug("sFuzz log_file: ", log_file)
        try:
            with open(log_file, "r", encoding="utf-8") as file:
                lines = [line.rstrip() for line in file]
        except Exception as err:
            error_traceback(f"Failed to parse sFuzz log file: {log_file}\n\n{err}")
            return []

        contract_name = ""
        contract_lines = []
        contract_pairs = []
        for line in lines:
            if "Fuzzing contract:" in line:
                if contract_lines != []:
                    contract_pairs.append((contract_name, contract_lines))
                    contract_lines = []

                contract_name = line.removeprefix("Fuzzing contract: ")
                print(f"contract_name: {contract_name}")

            else:
                contract_lines.append(line)

        if contract_lines != []:
            contract_pairs.append((contract_name, contract_lines))

        all_bugs = []
        for (contract_name, contract_lines) in contract_pairs:
            line = contract_lines[-1]
            parts = line.split()
            if len(parts) >= 3:
                line = line.removeprefix(parts[0] + " ")
                line = line.removeprefix(parts[1] + " ")
                try:
                    data = json.loads(line)
                    bugs = data[contract_name]["bugs"]
                    if bugs is not None:
                        all_bugs += list(bugs.keys())

                except Exception:
                    continue

        print(all_bugs)
        issues = []
        checker = Checker("ILF", "fuzzing")
        location = self.parse_issue_location(log_file)

        for bug in all_bugs:
            kind = self.parse_issue_kind(bug)
            issue = Issue(
                kind,
                "",
                Severity.UNKNOWN,
                Confidence.UNKNOWN,
                location,
                checker,
            )
            issues.append(issue)

        return issues

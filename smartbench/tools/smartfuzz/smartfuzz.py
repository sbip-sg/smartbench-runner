def parse_smartfuzz_json_output(
    output_file: str,
    log_file: str,
) -> List[Issue]:
    """Parse output of Smartfuzz"""
    output = None

    debug("Smartfuzz parse file: ", output_file)
    with open(output_file, "r", encoding="utf-8") as file:
        try:
            output = json.load(file)
        except ValueError:
            warning("Failed to parse Smartfuzz output file:", output_file)
            return []

    if output is None:
        warning("Failed to parse Smartfuzz's output file:", output_file)
        return []

    try:
        success = output.get("success")
        if not success:
            warning("An error happened when running Smartfuzz!")
            warning("See output file for more details: " + output_file)
            return []

        results = output.get("results")
        detectors = results.get("detectors")

        issues = []

        for detector in detectors:
            description = detector.get("description")
            checker = parse_rule(detector.get("check"))
            kind = parse_issue_kind(description, checker.detector)
            location = parse_source_location(log_file, detector.get("elements"))
            severity = parse_severity(detector.get("impact"))
            confidence = parse_confidence(detector.get("confidence"))
            issue = Issue(
                kind,
                description,
                severity,
                confidence,
                location,
                checker,
            )
            issues.append(issue)

        return issues
    except ValueError:
        return []

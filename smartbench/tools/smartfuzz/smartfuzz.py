def make_smartfuzz_analysis_command(
    executable_file: str,
    arguments: str,
    test_file: str,
    output_file: str,
    solc_path: str,
):
    """
    Function to make analysis command for Smartfuzz.
    This function should have the same signature with other tools.
    """
    command = executable_file

    if arguments:
        command = command + " " + arguments

    command = (
        command
        + " --path "
        + test_file
        + " -r "
        + output_file
        + " --rust-evm"
        + " --trials 40000"
    )

    print(f"command: {command}");
    return command


def parse_confidence(confidence: Union[str, None]) -> Confidence:
    """Parse confidence level of issue detected by Smartfuzz."""
    if confidence is None:
        return Confidence.UNKNOWN

    confidence = confidence.casefold()

    if confidence == "high":
        return Confidence.HIGH

    if confidence == "low":
        return Confidence.LOW

    if confidence == "medium":
        return Confidence.MEDIUM

    return Confidence.UNKNOWN


def parse_severity(severity: Union[str, None]) -> Severity:
    """Parse severity level of issue detected by Smartfuzz."""
    if severity is None:
        return Severity.UNKNOWN

    severity = severity.casefold()

    if severity == "optimization":
        return Severity.CODE_OPTIMIZATION

    if severity == "informational":
        return Severity.INFORMATIONAL

    if severity == "low":
        return Severity.LOW_RISK

    if severity == "medium":
        return Severity.MEDIUM_RISK

    if severity == "high":
        return Severity.HIGH_RISK

    return Severity.UNKNOWN


def parse_source_location(log_file, backtrace_elements) -> Location:
    """Parse source location in backtrace elements generated by Smartfuzz."""
    if len(backtrace_elements) == 0:
        test_file = log.get_input_test_file(log_file)
        return Location(test_file)

    buggy_element = backtrace_elements[0]
    source_mapping = buggy_element.get("source_mapping")
    file_name = source_mapping.get("filename_absolute")
    lines = source_mapping.get("lines")
    start_line = lines[0]
    end_line = lines[len(lines) - 1]
    start_column = source_mapping.get("starting_column")
    end_column = source_mapping.get("ending_column")

    return Location(file_name, start_line, start_column, end_line, end_column)



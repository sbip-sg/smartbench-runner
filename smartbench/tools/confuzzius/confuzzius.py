# Library
from smartbench import bug_annot, log
from smartbench.bug_annot import BugAnnot
from smartbench.debug import debug, warning
from smartbench.issue import Checker, Confidence, Issue, IssueKind, Severity
from smartbench.location import Location


# Tool name
TOOL_NAME = "ConFuzzius"

def make_analysis_command(
    executable_file: str,
    arguments: str,
    test_file: str,
    output_file: str,
    solc_path: str,
    timeout: int,
):
    """
    Function to make analysis command for Confuzzius.
    This function should have the same signature with other tools.
    """
    command = executable_file

    if arguments:
        command = command + " " + arguments

    command = (
        command
        + " -s "
        + test_file
        + " -r "
        + output_file
        + " --evm byzantium"
        + " -t "
        + str(timeout)
    )
    return command


def parse_severity(severity: Optional[str]) -> Severity:
    """Parse severity level of issue detected by Confuzzius."""
    if severity is None:
        return Severity.UNKNOWN

    severity = severity.casefold()

    if severity == "low":
        return Severity.LOW_RISK

    if severity == "medium":
        return Severity.MEDIUM_RISK

    if severity == "high":
        return Severity.HIGH_RISK

    return Severity.UNKNOWN


def parse_source_location(log_file: str, line, col) -> Optional[Location]:
    """Parse source location in backtrace elements generated by Confuzzius."""
    file_path = log.get_input_test_file(log_file)
    return Location(file_path, line, col, line, col)


def parse_rule(rule: str) -> Checker:
    """Parser checker of Confuzzius"""
    return Checker("Confuzzius", rule)


def parse_issue_kind(description: str) -> IssueKind:
    """Parse issue kind from issue description reported by Confuzzius"""
    if "Reentrancy" in description:
        return IssueKind.REENTRANCY

    if "Assertion Failure" in description:
        return IssueKind.ASSERTION_FAILURE

    if "Integer Overflow" in description:
        return IssueKind.INTEGER_BUG

    if "Integer Underflow" in description:
        return IssueKind.INTEGER_BUG

    if "Transaction Order Dependency" in description:
        return IssueKind.TRANSACTION_ORDER_DEPENDENCY

    if "Block Dependency" in description:
        return IssueKind.BLOCK_DEPENDENCY

    if "Leaking Ether" in description:
        return IssueKind.LEAKING_ETHER

    if "Locking Ether" in description:
        return IssueKind.LOCKING_ETHER

    if "Unchecked Return Value" in description:
        return IssueKind.UNHANDLED_EXCEPTION

    if "Unprotected Selfdestruct" in description:
        return IssueKind.UNSAFE_SELFDESTRUCT

    if "Unsafe Delegatecall" in description:
        return IssueKind.UNSAFE_DELEGATECALL

    return IssueKind.UNKNOWN


def parse_confuzzius_json_output(
    output_file: str,
    log_file: str,
) -> List[Issue]:
    """Parse output of Confuzzius"""
    output = None

    debug("Confuzzius parse file: ", output_file)
    with open(output_file, "r", encoding="utf-8") as file:
        try:
            output = json.load(file)
        except ValueError:
            warning("Failed to parse Confuzzius output file:", output_file)
            return []

    if output is None:
        warning("Failed to parse Confuzzius's output file:", output_file)
        return []

    checker = parse_rule("fuzzing")
    try:
        issues = []

        all_results = list(output.values())
        results = all_results[0]
        error_list = results.get("errors")
        errors = list(error_list.values())

        for error_desc in errors:
            error = error_desc[0]
            kind = parse_issue_kind(error.get("type"))
            location = parse_source_location(
                log_file, error.get("line"), error.get("column")
            )
            severity = parse_severity(error.get("severity"))
            issue = Issue(
                kind,
                "",
                severity,
                Confidence.UNKNOWN,
                location,
                checker,
            )
            issues.append(issue)
        return issues

    except ValueError:
        return []


def check_issue_kind(kind: IssueKind, bug_name: str):
    if kind == IssueKind.TRANSACTION_ORDER_DEPENDENCY:
        return bug_name == "FRONT_RUNNING"

    if kind == IssueKind.INTEGER_BUG:
        return bug_name == "ARITHMETIC"

    if kind == IssueKind.UNHANDLED_EXCEPTION:
        return bug_name == "UNCHECKED_LL_CALLS"

    if str(kind).casefold() != bug_name.casefold():
        return False
    return True


def match_location_of_issue_to_annotation(issue: Issue, annot: BugAnnot):
    """Function to check whether an reported issue is related to a bug
    annotation."""

    # Check for issue kind
    if not check_issue_kind(issue.issue_kind, annot.bug_name):
        return False

    iloc: Location = issue.location
    # Check whether the issue location is covered by the annotation location.
    if iloc.start_line is None or iloc.end_line is None:
        return False
    if iloc.start_line < annot.start_line + 1:
        return False
    if iloc.end_line > annot.end_line + 1:
        return False

    # Pass all criteria to match an issue with a bug annotation
    return True

#!/usr/bin/env python3

"""Module handling Confuzzius"""

# Standard Library
import json
import math
import os

from typing import List, Optional

# Library
from smartbench import issue, logger
from smartbench.annotation import BugAnnot
from smartbench.docker import DockerContainer
from smartbench.issue import Checker, Confidence, Issue, IssueKind, Severity
from smartbench.printer import debug, error_traceback
from smartbench.solidity.loc import Location
from smartbench.tools.tool import Tool


class Confuzzius(Tool):
    def __init__(
        self,
        id: str,
        name: str,
        executable: str,
        default_args: str,
        default_timeout: int,
        additional_args: Optional[str] = None,
        random_seed: int = 0,
    ):
        Tool.__init__(
            self,
            id,
            name,
            executable,
            default_args,
            default_timeout,
            additional_args,
            random_seed,
        )

    def make_analysis_command(
        self,
        test_file: str,
        contracts: List[str],
        test_output_dir: str,
        solc_version: str,
        container=DockerContainer,
        timeout: Optional[int] = None,
        **kwargs,
    ) -> str:
        """
        Function to make an analysis command for Slither.
        """

        # Configure command
        cmd = f"docker exec -it {container.name} /root/{self.executable}"

        # Input file and contract names
        cmd = cmd + " -f " + test_file
        if len(contracts) == 1:
            cmd = cmd + " -c " + contracts[0]

        # Solc version
        if solc_version is not None:
            cmd = cmd + " --solc-version " + solc_version

        # Output directory
        cmd = cmd + " -o " + test_output_dir

        # Timeout for each contract
        timeout = self.default_timeout if timeout is None else timeout
        contract_timeout = math.ceil(timeout / len(contracts))
        cmd = cmd + " -t " + str(contract_timeout)

        # Tool ID (Confuzzius has multiple variants)
        cmd = cmd + " --tool-id " + self.id

        # Finally, pass default and additional arguments
        if self.default_arguments:
            cmd = cmd + " " + self.default_arguments
        if self.additional_args:
            cmd = cmd + " " + self.additional_args

        return cmd

    def parse_issue_severity(self, severity: Optional[str]) -> Severity:
        if severity is None:
            return Severity.UNKNOWN

        severity = severity.casefold()

        if severity == "low":
            return Severity.LOW_RISK

        if severity == "medium":
            return Severity.MEDIUM_RISK

        if severity == "high":
            return Severity.HIGH_RISK

        return Severity.UNKNOWN

    def parse_source_location(self, log_file: str, line, col) -> Location:
        """Parse source location in backtrace elements generated by Confuzzius."""
        file_path = logger.get_input_test_file(log_file)
        return Location(file_path, line, col, line, col)

    def parse_issue_kind(self, type: str) -> IssueKind:
        """Parse issue kind from issue description reported by Confuzzius"""
        if "Reentrancy" in type:
            return IssueKind.REENTRANCY

        if "Assertion Failure" in type:
            return IssueKind.ASSERTION_FAILURE

        if "Arbitrary Memory Access" in type:
            return IssueKind.WRITE_TO_ARBITRARY_STORAGE_LOCATION

        if "Integer Overflow" in type:
            return IssueKind.INTEGER_OVERFLOW

        if "Integer Underflow" in type:
            return IssueKind.INTEGER_UNDERFLOW

        if "Transaction Order Dependency" in type:
            return IssueKind.TRANSACTION_ORDER_DEPENDENCY

        if "Block Dependency" in type:
            return IssueKind.BLOCK_VALUE_DEPENDENCY

        if "Leaking Ether" in type:
            return IssueKind.LEAKING_ETHER

        if "Locking Ether" in type:
            return IssueKind.LOCKING_ETHER

        if "Unchecked Return Value" in type:
            return IssueKind.UNHANDLED_EXCEPTION

        if "Unprotected Selfdestruct" in type:
            return IssueKind.UNSAFE_SELFDESTRUCT

        if "Unsafe Delegatecall" in type:
            return IssueKind.UNSAFE_DELEGATECALL

        return IssueKind.UNKNOWN

    def parse_analysis_output(
        self,
        test_output_dir: str,
    ) -> Optional[List[Issue]]:
        """Parse output of Confuzzius"""
        log_file = self.configure_log_file(test_output_dir)
        output_file = self.configure_json_output(test_output_dir)

        if output_file is None:
            error_traceback("JSON output file is not found!")
            return None

        debug("Confuzzius parse file: ", output_file)
        output = None
        try:
            with open(output_file, "r", encoding="utf-8") as file:
                output = json.load(file)
        except Exception:
            error_traceback(f"Failed to parse Confuzzius output: {output_file}")
            return None

        checker = Checker("Confuzzius", "fuzzing")
        all_issues = []

        contracts = list(output.keys())
        for contract in contracts:
            contract_results = output.get(contract)

            # Confuzzius groups bugs by location
            bug_groups = list(contract_results.get("errors").values())

            for bug_group in bug_groups:
                for bug in bug_group:
                    kind = self.parse_issue_kind(bug.get("type"))
                    location = self.parse_source_location(
                        log_file,
                        bug.get("line"),
                        bug.get("column"),
                    )
                    severity = self.parse_issue_severity(bug.get("severity"))

                    # Do not add duplicated issues
                    all_issues = issue.update_new_issue(
                        all_issues,
                        kind,
                        "",
                        severity,
                        Confidence.UNKNOWN,
                        location,
                        checker,
                    )
        return all_issues

    def match_location_of_issue_to_annotation(
        self, issue: Issue, annot: BugAnnot
    ) -> bool:
        """Check whether the location of an issue is relevant to the location of
        a bug annotation.
        """

        if issue.location is None:
            return False

        iloc = issue.location

        # The bug line number must be reported explicitly by Confuzzius
        if iloc.start_line is None or iloc.end_line is None:
            return False

        # Confuzzius reports issue location as a single point: line and column.
        # If an issue and a bug annotation are relevant, then the bug
        # annotation's location should cover the issue's location.

        return (
            iloc.start_line >= annot.start_line
            and iloc.end_line <= annot.end_line
        )

    def parse_instruction_coverage(self, test_output_dir: str):
        """Parse code coverage of Confuzzius"""
        output_file = self.configure_json_output(test_output_dir)
        output = None
        try:
            with open(output_file, "r", encoding="utf-8") as file:
                output = json.load(file)
        except Exception:
            error_traceback(f"Failed to parse Confuzzius output: {output_file}")
            return None

        contract_coverage_list = []
        first_coverage = (0, 0)
        contracts = list(output.keys())
        for contract in contracts:
            contract_results = output.get(contract)
            generations = contract_results.get("generations")
            contract_coverage = [first_coverage]
            current_time = 0
            if generations is not None:
                for generation in generations:
                    time = float("{:.1f}".format(generation.get("time")))
                    coverage = float(
                        "{:.1f}".format(generation.get("code_coverage"))
                    )
                    if time - current_time >= 1:
                        contract_coverage.append((time, coverage))
                        current_time = time

            contract_coverage_list.append((contract, contract_coverage))

        if contract_coverage_list == []:
            return None

        results_json_obj = {
            "coverage-interval": -1,
        }
        for contract_name, contract_coverage in contract_coverage_list:
            results_json_obj[contract_name] = contract_coverage

        results_json_obj_str = json.dumps(results_json_obj, indent=2)
        debug(f"coverage: {results_json_obj_str}")

        coverage_file = os.path.join(test_output_dir, self.coverage_json_file)
        with open(coverage_file, "w", encoding="utf-8") as file:
            file.write(results_json_obj_str)
            file.close()

        return coverage_file
